use super::{dmat::DMat, drvec::DRVec, field::Field};

pub struct DCVec<F: Field> {
    data: Vec<F::Element>,
}

// ---------------------------------------------------------------------------------------------------------------------
// ---------------------------------------------------------------------------------------------------------------------
// Column vector getters -----------------------------------------------------------------------------------------------
// ---------------------------------------------------------------------------------------------------------------------
// ---------------------------------------------------------------------------------------------------------------------

impl<F: Field> DCVec<F> {
    pub fn rows(&self) -> usize {
        self.data.len()
    }
}

// ---------------------------------------------------------------------------------------------------------------------
// ---------------------------------------------------------------------------------------------------------------------
// Column vector creation ----------------------------------------------------------------------------------------------
// ---------------------------------------------------------------------------------------------------------------------
// ---------------------------------------------------------------------------------------------------------------------

impl<F: Field> From<Vec<F::Element>> for DCVec<F> {
    fn from(col: Vec<F::Element>) -> Self {
        Self { data: col }
    }
}

impl<F: Field> DCVec<F> {
    pub fn zeros(rows: usize) -> Self {
        vec![F::ZERO; rows].into()
    }
}

// ---------------------------------------------------------------------------------------------------------------------
// ---------------------------------------------------------------------------------------------------------------------
// Column vector unary operations --------------------------------------------------------------------------------------
// ---------------------------------------------------------------------------------------------------------------------
// ---------------------------------------------------------------------------------------------------------------------

impl<F: Field> DCVec<F> {
    pub fn transpose(&self) -> DRVec<F> {
        self.data.clone().into()
    }

    pub fn into_transpose(self) -> DRVec<F> {
        self.data.into()
    }
}

// ---------------------------------------------------------------------------------------------------------------------
// ---------------------------------------------------------------------------------------------------------------------
// Column vector binary operations -------------------------------------------------------------------------------------
// ---------------------------------------------------------------------------------------------------------------------
// ---------------------------------------------------------------------------------------------------------------------

impl<F: Field> std::ops::Mul<&DCVec<F>> for &DMat<F> {
    type Output = DCVec<F>;

    fn mul(self, rhs: &DCVec<F>) -> Self::Output {
        debug_assert_eq!(
            self.cols(),
            rhs.rows(),
            "matrix dimentions do not match for multiplication"
        );

        let mut res = DCVec::zeros(self.rows());

        for (a_row, res_val) in self.rows_iter().zip(res.data.iter_mut()) {
            for (a_val, b_val) in a_row.iter().zip(rhs.data.iter()) {
                *res_val = F::add(res_val, &F::mul(a_val, b_val));
            }
        }

        res
    }
}

// ---------------------------------------------------------------------------------------------------------------------
// ---------------------------------------------------------------------------------------------------------------------
// Column vector formatting --------------------------------------------------------------------------------------------
// ---------------------------------------------------------------------------------------------------------------------
// ---------------------------------------------------------------------------------------------------------------------

impl<F: Field> std::fmt::Debug for DCVec<F>
where
    F::Element: std::fmt::Debug,
{
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("DCVec").field("data", &self.data).finish()
    }
}

impl<F: Field> std::fmt::Display for DCVec<F>
where
    F::Element: std::fmt::Display,
{
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let self_str: String = self
            .data
            .iter()
            .map(|n| format!("|{n}|"))
            .collect::<Vec<_>>()
            .join("\n");
        write!(f, "{self_str}")
    }
}

// ---------------------------------------------------------------------------------------------------------------------
// ---------------------------------------------------------------------------------------------------------------------
// Column vector equality ----------------------------------------------------------------------------------------------
// ---------------------------------------------------------------------------------------------------------------------
// ---------------------------------------------------------------------------------------------------------------------

impl<F: Field> PartialEq for DCVec<F> {
    fn eq(&self, other: &Self) -> bool {
        self.data == other.data
    }
}

impl<F: Field> Eq for DCVec<F> {}

// ---------------------------------------------------------------------------------------------------------------------
// ---------------------------------------------------------------------------------------------------------------------
// Column vector hash --------------------------------------------------------------------------------------------------
// ---------------------------------------------------------------------------------------------------------------------
// ---------------------------------------------------------------------------------------------------------------------

impl<F: Field> std::hash::Hash for DCVec<F> {
    fn hash<H: std::hash::Hasher>(&self, state: &mut H) {
        self.data.hash(state);
    }
}

// ---------------------------------------------------------------------------------------------------------------------
// ---------------------------------------------------------------------------------------------------------------------
// Column vector cloning -----------------------------------------------------------------------------------------------
// ---------------------------------------------------------------------------------------------------------------------
// ---------------------------------------------------------------------------------------------------------------------

impl<F: Field> Clone for DCVec<F> {
    fn clone(&self) -> Self {
        Self {
            data: self.data.clone(),
        }
    }
}
